from __future__ import annotations

import argparse
from collections import Counter
from pathlib import Path
from typing import Iterable, List, Optional

from scripts.research_registry import ResearchRow, read_registry, validate_rows


SECTION_LABELS = {
    "model": "Models",
    "loss": "Losses and objectives",
    "setting": "Settings and protocols",
    "metric": "Metrics",
    "sampler": "Samplers",
    "benchmark": "Benchmarks",
}


def _escape(value: str) -> str:
    return value.replace("|", "\\|").replace("\n", " ")


def _tokens(values: Iterable[str]) -> str:
    return ", ".join(f"`{value}`" for value in values) or "-"


def _link(label: str, url: str) -> str:
    return f"[{_escape(label)}]({url})"


def render_atlas(rows: List[ResearchRow], registry_path: Path) -> str:
    publication_counts = Counter(row.publication_status for row in rows)
    maturity_counts = Counter(row.implementation_maturity for row in rows)

    lines = [
        "# 2025-2026 Method Atlas",
        "",
        f"> Generated from `{registry_path.as_posix()}`. Do not edit this file manually.",
        "> Registry presence is research evidence, not a release-support or benchmark-valid claim.",
        "",
        "Re-generate and validate:",
        "",
        "```bash",
        "python -m scripts.validate_research_registry",
        "python -m scripts.gen_research_atlas",
        "```",
        "",
        "## Status summary",
        "",
        f"- Methods: `{len(rows)}`",
        "- Publication: "
        + ", ".join(f"`{key}={publication_counts[key]}`" for key in sorted(publication_counts)),
        "- Implementation: "
        + ", ".join(f"`{key}={maturity_counts[key]}`" for key in sorted(maturity_counts)),
        "",
    ]

    for kind, label in SECTION_LABELS.items():
        section_rows = sorted(
            (row for row in rows if kind in row.contribution_kinds),
            key=lambda row: (row.year, row.method_id),
        )
        if not section_rows:
            continue
        lines.extend(
            [
                f"## {label}",
                "",
                "| Method | Evidence | Tasks | Maturity | Recommendation | "
                "Code/license | Repository mapping |",
                "| --- | --- | --- | --- | --- | --- | --- |",
            ]
        )
        for row in section_rows:
            evidence = (
                f"{row.year}; `{row.publication_status}`; "
                + _link(row.venue or row.identifier, row.publication_record_url or row.paper_url)
            )
            if row.code_url:
                code = _link("code", row.code_url) + f"; `{row.code_license_status}`"
                if row.code_license_expression:
                    code += f" ({_escape(row.code_license_expression)})"
            else:
                code = "-"
            lines.append(
                "| "
                + " | ".join(
                    [
                        _link(row.title, row.paper_url),
                        evidence,
                        _tokens(row.task_families),
                        f"`{row.implementation_maturity}`",
                        f"`{row.recommendation}`",
                        code,
                        f"`{_escape(row.repo_mapping)}`" if row.repo_mapping else "-",
                    ]
                )
                + " |"
            )
        lines.append("")

    lines.extend(
        [
            "## Interpretation rules",
            "",
            "- `preprint` and `submission` entries remain `research_only` at most.",
            "- `unknown` or `conflicting` code licenses prohibit vendoring or copying source.",
            "- `experimental_candidate` means selected for local implementation, "
            "not validated runtime support.",
            "- Promotion to `benchmark_candidate` requires repository-local, "
            "leakage-safe, repeated-run evidence.",
            "",
        ]
    )
    return "\n".join(lines)


def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(description="Generate the 2025-2026 research method atlas")
    parser.add_argument("--registry", default="research/2025_2026/method_registry.csv")
    parser.add_argument("--out", default="docs/research/2025_2026_METHOD_ATLAS.md")
    args = parser.parse_args(argv)

    registry_path = Path(args.registry)
    rows = read_registry(registry_path)
    errors = validate_rows(rows)
    if errors:
        raise ValueError("invalid research registry:\n- " + "\n- ".join(errors))

    out_path = Path(args.out)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(render_atlas(rows, registry_path), encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
